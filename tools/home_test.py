"""Test headless de l'accueil : pages (glisser, onglets), paramètres, arbre, retour.   python tools/home_test.py"""
import functools, http.server, re, threading, sys, os
from playwright.sync_api import sync_playwright
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self,*a): pass
srv=http.server.ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Q,directory=R))
threading.Thread(target=srv.serve_forever,daemon=True).start()
errs=[]
def ck(c,m): print(('ok     ' if c else 'ECHEC  ')+m)
with sync_playwright() as pw:
    b=pw.chromium.launch(channel='chrome'); p=b.new_page(viewport={'width':420,'height':760})
    p.on('pageerror',lambda e:errs.append(str(e)))
    p.route('**/phaser.min.js',lambda r:r.fulfill(path=R+'/vendor/phaser.min.js'))
    p.route('**/fonts.googleapis.com/**',lambda r:r.fulfill(status=200,content_type='text/css',body=''))
    p.goto('http://127.0.0.1:%d/index.html'%srv.server_address[1])
    p.wait_for_function('window.__ssxScene && window.__ssxScene.scene.isActive("home")',timeout=60000); p.wait_for_timeout(800)
    vis=lambda s: p.evaluate("!document.querySelector('%s').classList.contains('hidden')"%s)
    ck(vis('#home') and not vis('#start'),'accueil visible, ancien menu masqué')
    ck(p.evaluate("document.getElementById('tabMap').classList.contains('on')"),'onglet CARTE actif au départ')
    # 1re partie (progression vide) : DECOLLER lance le tuto, qui ramène ensuite à l'accueil
    p.evaluate("document.getElementById('btnLaunch').click()"); p.wait_for_timeout(2500)
    ck(p.evaluate("window.__ssxScene.tuto===true && window.__ssxScene.running"),'1re partie : DECOLLER lance le tuto')
    p.evaluate("window.__ssxScene.tutoFinish()"); p.wait_for_timeout(1800)
    ck(p.evaluate("window.__ssxScene.scene.isActive('home') && !document.getElementById('home').classList.contains('hidden')"),'fin du tuto : retour à l\'accueil')
    p.mouse.click(380,30); p.wait_for_timeout(500)       # engrenage (vrai clic)
    ck(vis('#settingsMenu'),'engrenage ouvre les paramètres')
    p.evaluate("document.getElementById('btnSettingsBack').click()"); p.wait_for_timeout(500)
    ck(vis('#home') and not vis('#settingsMenu') and not vis('#start'),'retour des paramètres -> accueil')
    # glisser vers la droite (page ARBRE) puis vers la gauche x2 (HANGAR)
    def swipe(x0,x1,y=420):
        p.mouse.move(x0,y); p.mouse.down(); p.mouse.move((x0+x1)//2,y); p.mouse.move(x1,y); p.mouse.up(); p.wait_for_timeout(700)
    page=lambda: p.evaluate("window.__ssxScene.scene.get('home').page")
    swipe(300,80); ck(page()==1,'glisser vers la gauche -> page ARBRE')
    swipe(6,320); ck(page()==0,'glisser vers la droite depuis le bord (arbre) -> CARTE')
    swipe(80,320); ck(page()==-1,'glisser vers la droite -> HANGAR')
    # arbre : page de droite, achat, fragments mis à jour
    p.evaluate("localStorage.setItem('ssx_meta_v2', JSON.stringify({fragments:500,tree:{},asc:0}))")
    p.evaluate("(()=>{ const h=window.__ssxScene.scene.get('home'); h.scene.sleep(); h.scene.wake(); })()"); p.wait_for_timeout(600)
    p.evaluate("document.getElementById('tabTree').click()"); p.wait_for_timeout(900)
    ck(page()==1 and p.evaluate("document.querySelectorAll('#treeScroll .tcard').length")>1,"l'arbre s'affiche dans la page de droite")
    ck(p.evaluate("document.getElementById('tabTree').classList.contains('buy')"),'point doré : un achat est possible')
    ck(p.evaluate("!!(document.getElementById('btnAscend') || document.getElementById('alertRowSkills') || document.querySelector('#treeRings'))")==False,"plus d'ascension ni d'anneaux d'alerte")
    p.evaluate("document.querySelector('#treeScroll .tcard.aff').dispatchEvent(new MouseEvent('click',{bubbles:true}))"); p.wait_for_timeout(300)
    ck(p.evaluate("!document.getElementById('treeInvestBtn').disabled"),'nœud abordable sélectionné : bouton + actif')
    p.evaluate("document.getElementById('treeInvestBtn').click()"); p.wait_for_timeout(500)
    ck(p.evaluate("getMeta().fragments")<500 and p.evaluate("document.getElementById('homeFrag').textContent").strip()==str(p.evaluate("getMeta().fragments")),'achat : fragments débités et affichage mis à jour')
    # Garage illustré : un seul atelier et modules purement visuels.
    p.evaluate("document.getElementById('tabHangar').click()"); p.wait_for_timeout(700)
    assert p.locator('#atelierNext').is_visible()
    assert p.locator('#atelierVersion').count()==0
    assert not p.evaluate("window.__ssxScene.scene.get('home').van.visible")
    p.locator('.an-cards button').nth(1).click()
    assert 'aimant' in p.locator('#anModule').get_attribute('src')
    p.locator('.an-cards button').nth(2).click()
    assert 'canon' in p.locator('#anModule').get_attribute('src')
    assert p.evaluate("localStorage.getItem('ssx_atelier_preview_module')")=='cannon'
    p.locator('.an-cards button').nth(0).click()
    assert p.locator('#anModule').is_hidden()
    for category in ['paint','body','modules']:
        p.locator('[data-section='+category+']').click()
    ck(True,'garage unique : ajout/retrait des modules et catégories')
    p.evaluate("document.getElementById('tabTree').click()"); p.wait_for_timeout(700)
    # arbre : glisser sur les onglets de branche = les faire défiler (pas de changement de page) ; ailleurs = changer de page
    ty=p.evaluate("(()=>{const r=document.getElementById('treeTabs').getBoundingClientRect(); return Math.round(r.top+r.height/2)})()")
    swipe(300,120,y=ty); ck(page()==1,"glisser sur les onglets de l'arbre ne change pas de page")
    swipe(80,330,y=500); ck(page()==0,"glisser vers la droite sur les cartes -> retour à la carte")
    # carte stellaire
    mode=lambda: p.evaluate("window.__ssxScene.scene.get('home').mapMode")
    p.evaluate("document.getElementById('tabMap').click()"); p.wait_for_timeout(500)
    p.evaluate("document.getElementById('tabMap').click()"); p.wait_for_timeout(1500)
    ck(mode()=='galaxy' and p.evaluate("document.getElementById('pageMap').dataset.mode")=='galaxy','onglet CARTE -> carte stellaire')
    gy=lambda: p.evaluate("window.__ssxScene.scene.get('home').galY")
    y0=gy(); p.mouse.move(200,300); p.mouse.down(); p.mouse.move(200,360); p.mouse.move(200,420); p.mouse.up(); p.wait_for_timeout(900)
    ck(gy()!=y0,'défilement vertical au doigt')
    pos=p.evaluate("(()=>{const h=window.__ssxScene.scene.get('home'); return h.galWorlds.map(g=>[g.pos.x,g.pos.y+h.galY]) })()")
    p.mouse.click(pos[1][0],pos[1][1]); p.wait_for_timeout(500)
    ck(mode()=='galaxy' and p.evaluate("document.getElementById('homeToast').classList.contains('show')"),'monde verrouillé : message, on reste sur la carte')
    p.mouse.click(pos[0][0],pos[0][1]); p.wait_for_timeout(2200)
    ck(mode()=='world' and p.evaluate("document.getElementById('mwName').textContent")=='ORBITE TERRESTRE','toucher un monde ouvert -> vue du monde')
    sel=p.evaluate("window.__ssxScene.scene.get('home').homeSel")
    prow=p.evaluate("(()=>{ const r=[...document.querySelectorAll('.om-row')].find(x=>x.textContent.indexOf('PRIME')>=0); return r ? r.textContent : ''; })()")
    pv=p.evaluate("composantsPrime(levelById('%s').reward, false)" % sel)
    ck(re.search(r'\+%d(?!\d)' % pv, prow) is not None,'fiche d\'ordre : prime AGP affichée (+%s dans « %s »)' % (pv, prow))
    ck(p.evaluate("document.querySelectorAll('#mapOrbit .node').length")==6,'6 niveaux en orbite (tuto + 5)')
    # déblocage animé : monde 1 terminé -> le monde 2 se débloque au retour sur l'accueil
    p.evaluate("localStorage.setItem('ssx_worlds_v1', JSON.stringify({v:1,levels:{'w1-l1':{clears:1,best:5},'w1-l2':{clears:1,best:5},'w1-l3':{clears:1,best:5},'w1-l4':{clears:1,best:5},'w1-l5':{clears:1,best:5}},seen:{},last:'w1-l5'}))")
    p.evaluate("(()=>{ const h=window.__ssxScene.scene.get('home'); h.scene.sleep(); h.scene.wake(); })()"); p.wait_for_timeout(500)
    p.wait_for_function("window.__ssxScene.scene.get('home').mapMode==='galaxy'", timeout=30000); p.wait_for_timeout(500)
    ck(p.evaluate("wasWorldSeen('w:w2')") and p.evaluate("document.getElementById('homeToast').textContent").startswith('NOUVEAU SECTEUR'),'nouveau monde : animation de déblocage jouée une fois')
    pos=p.evaluate("(()=>{const h=window.__ssxScene.scene.get('home'); return h.galWorlds.map(g=>[g.pos.x,g.pos.y+h.galY]) })()")
    p.mouse.click(pos[1][0],pos[1][1]); p.wait_for_timeout(2200)
    ck(mode()=='world' and p.evaluate("document.getElementById('mwName').textContent")=='LA CASSE LUNAIRE','le monde 2 est maintenant ouvert')
    p.evaluate("(()=>{ const h=window.__ssxScene.scene.get('home'); h.scene.sleep(); h.scene.wake(); })()"); p.wait_for_timeout(800)
    ck(mode()=='world' and not p.evaluate("wasWorldSeen('w:w2')")==False,'à nouveau sur l\'accueil : pas de rejeu de l\'animation')
    b.close()
print('erreurs JS:',errs)
sys.exit(1 if errs else 0)
